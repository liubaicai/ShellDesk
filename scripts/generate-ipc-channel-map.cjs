const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');

const root = path.resolve(__dirname, '..');
const bridgePath = path.join(root, 'src', 'tauriBridge.ts');
const outputPath = path.join(root, 'src', 'ipcChannelMap.ts');
const sourceText = fs.readFileSync(bridgePath, 'utf8').replace(/\r\n/g, '\n');
const sourceFile = ts.createSourceFile(bridgePath, sourceText, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
const declarations = new Map();

function visitDeclarations(node) {
  if (ts.isFunctionDeclaration(node) && node.name) {
    declarations.set(node.name.text, node);
  }
  if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.initializer) {
    declarations.set(node.name.text, node.initializer);
  }
  ts.forEachChild(node, visitDeclarations);
}

visitDeclarations(sourceFile);

function propertyName(node) {
  if (ts.isIdentifier(node) || ts.isStringLiteral(node)) return node.text;
  return null;
}

function resolveNode(node) {
  if (ts.isIdentifier(node) && declarations.has(node.text)) {
    return declarations.get(node.text);
  }
  return node;
}

function collectIpcChannels(node) {
  const channels = new Set();
  const resolved = resolveNode(node);

  function visit(current) {
    if (
      ts.isCallExpression(current)
      && ts.isIdentifier(current.expression)
      && current.expression.text === 'ipc'
      && current.arguments.length > 0
      && ts.isStringLiteral(current.arguments[0])
    ) {
      channels.add(current.arguments[0].text);
    }
    ts.forEachChild(current, visit);
  }

  visit(resolved);
  return [...channels];
}

let apiObject = null;

function findApiObject(node) {
  if (
    ts.isBinaryExpression(node)
    && node.operatorToken.kind === ts.SyntaxKind.EqualsToken
    && ts.isPropertyAccessExpression(node.left)
    && ts.isIdentifier(node.left.expression)
    && node.left.expression.text === 'window'
    && node.left.name.text === 'guiSSH'
    && ts.isObjectLiteralExpression(node.right)
  ) {
    apiObject = node.right;
    return;
  }
  ts.forEachChild(node, findApiObject);
}

findApiObject(sourceFile);
if (!apiObject) throw new Error('Could not find window.guiSSH assignment.');

const bindings = new Map();

function collectBindings(objectNode, prefix = []) {
  for (const property of objectNode.properties) {
    if (ts.isPropertyAssignment(property)) {
      const name = propertyName(property.name);
      if (!name) continue;
      const nextPrefix = [...prefix, name];
      if (ts.isObjectLiteralExpression(property.initializer)) {
        collectBindings(property.initializer, nextPrefix);
        continue;
      }
      for (const channel of collectIpcChannels(property.initializer)) {
        const apiPath = nextPrefix.join('.');
        const existingPath = bindings.get(channel);
        if (existingPath && existingPath !== apiPath) {
          throw new Error(`IPC channel ${channel} maps to both ${existingPath} and ${apiPath}.`);
        }
        bindings.set(channel, apiPath);
      }
      continue;
    }

    if (ts.isShorthandPropertyAssignment(property)) {
      const apiPath = [...prefix, property.name.text].join('.');
      for (const channel of collectIpcChannels(property.name)) {
        const existingPath = bindings.get(channel);
        if (existingPath && existingPath !== apiPath) {
          throw new Error(`IPC channel ${channel} maps to both ${existingPath} and ${apiPath}.`);
        }
        bindings.set(channel, apiPath);
      }
    }
  }
}

collectBindings(apiObject);

const allBridgeChannels = new Set();

function collectAllBridgeChannels(node) {
  if (
    ts.isCallExpression(node)
    && ts.isIdentifier(node.expression)
    && node.expression.text === 'ipc'
    && node.arguments.length > 0
    && ts.isStringLiteral(node.arguments[0])
  ) {
    allBridgeChannels.add(node.arguments[0].text);
  }
  ts.forEachChild(node, collectAllBridgeChannels);
}

collectAllBridgeChannels(sourceFile);
const missingBindings = [...allBridgeChannels].filter((channel) => !bindings.has(channel));
if (missingBindings.length > 0) {
  throw new Error(`IPC channels missing API bindings:\n${missingBindings.map((channel) => `  - ${channel}`).join('\n')}`);
}

const bindingLines = [...bindings.entries()]
  .sort(([first], [second]) => first.localeCompare(second))
  .map(([channel, apiPath]) => `  '${channel}': '${apiPath}',`);

const output = `// Generated by scripts/generate-ipc-channel-map.cjs. Do not edit by hand.
// The map binds each Rust IPC channel to the public guiSSH method that defines
// its renderer-facing argument tuple and return type.

export const ipcChannelBindings = {
${bindingLines.join('\n')}
} as const;

export type IpcChannel = keyof typeof ipcChannelBindings;

type AnyMethod = (...args: any[]) => any;
type PathValue<T, Path extends string> =
  Path extends \`\${infer Head}.\${infer Tail}\`
    ? Head extends keyof T
      ? PathValue<T[Head], Tail>
      : never
    : Path extends keyof T
      ? T[Path]
      : never;
type BoundMethod<Channel extends IpcChannel> = Extract<
  PathValue<ShellDeskApi, (typeof ipcChannelBindings)[Channel]>,
  AnyMethod
>;

interface IpcChannelSpec<Args extends unknown[], Result> {
  args: Args;
  result: Result;
}

interface IpcChannelOverrides {
  'ai:chat-stream': IpcChannelSpec<
    [request: ShellDeskAiChatRequest & { streamId: string }],
    ShellDeskAiChatResult
  >;
  'connection:connect': IpcChannelSpec<
    [host: ShellDeskHostConnectionRequest],
    { ok?: boolean; error?: string; connection?: ShellDeskConnectionInfo }
  >;
  'connection:open-local': IpcChannelSpec<
    [],
    { ok?: boolean; error?: string; connection?: ShellDeskConnectionInfo }
  >;
  'connection:run-command-stream': IpcChannelSpec<
    [
      connectionId: string,
      command: string,
      stdin: string | undefined,
      streamId: string,
      options?: { sudoPassword?: string },
    ],
    { stdout: string; stderr: string; code: number }
  >;
}

export type IpcChannelMap = {
  [Channel in IpcChannel]:
    Channel extends keyof IpcChannelOverrides
      ? IpcChannelOverrides[Channel]
      : IpcChannelSpec<
          Parameters<BoundMethod<Channel>>,
          Awaited<ReturnType<BoundMethod<Channel>>>
        >;
};

export type IpcArgs<Channel extends IpcChannel> = IpcChannelMap[Channel]['args'];
export type IpcResult<Channel extends IpcChannel> = IpcChannelMap[Channel]['result'];
`;

if (process.argv.includes('--write')) {
  fs.writeFileSync(outputPath, output, 'utf8');
  console.log(`Wrote ${path.relative(root, outputPath)} with ${bindings.size} channel bindings.`);
  process.exit(0);
}

const current = fs.existsSync(outputPath)
  ? fs.readFileSync(outputPath, 'utf8').replace(/\r\n/g, '\n')
  : '';
if (current !== output) {
  console.error('IPC channel map is stale. Run: node scripts/generate-ipc-channel-map.cjs --write');
  process.exit(1);
}

console.log(`IPC channel map ok: ${bindings.size} channels have typed API bindings.`);
